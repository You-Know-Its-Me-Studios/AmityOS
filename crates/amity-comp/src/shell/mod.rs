/// The fullscreen window of a monitor, kept in the monitor's user data.
///
/// The window manager owns the fullscreen state (`wm.rs`); this is what the
/// renderer and input routing look at.
#[derive(Default)]
pub struct FullscreenSurface {
    window: RefCell<Option<WindowElement>>,
    /// True while the window covers the whole monitor, hiding everything else.
    covering: Cell<bool>,
}

impl FullscreenSurface {
    pub fn set(&self, window: WindowElement) {
        *self.window.borrow_mut() = Some(window);
    }

    /// The monitor's fullscreen window, whether or not it covers it right now.
    pub fn get(&self) -> Option<WindowElement> {
        let mut window = self.window.borrow_mut();
        if window.as_ref().map(|w| !w.alive()).unwrap_or(false) {
            *window = None;
        }
        window.clone()
    }

    /// The fullscreen window when it covers the monitor: nothing else is drawn
    /// there and all pointer input on the monitor goes to it.
    pub fn covering(&self) -> Option<WindowElement> {
        if self.covering.get() {
            self.get()
        } else {
            None
        }
    }

    /// Returns whether the value changed.
    pub fn set_covering(&self, covering: bool) -> bool {
        self.covering.replace(covering) != covering
    }

    pub fn clear(&self) -> Option<WindowElement> {
        self.covering.set(false);
        self.window.borrow_mut().take()
    }
}

